// 词汇类型与运行时共用来源，--check 防止声明漂移。
import fs from 'node:fs';
import { VOCAB } from '../src/ai/vocab.js';
const names = { body: 'Body', prop: 'PropKind', pose: 'PosePreset', move: 'CameraMove', ratio: 'Ratio' };
const text = '// Generated by node scripts/type-vocab.mjs; do not edit.\n' + Object.entries(names)
  .map(([key, name]) => `export type ${name} = ${VOCAB[key].map(JSON.stringify).join(' | ')};`).join('\n') + '\n';
const file = 'src/types/vocab.d.ts';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(file, 'utf8') !== text) throw new Error('词汇类型已过期：运行 node scripts/type-vocab.mjs');
} else fs.writeFileSync(file, text);
